using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace Scott.Mail.Smtp2Go.Generators;

/// <summary>
/// The marker attributes the generators look for, added to every consuming compilation at initialisation so the library needs no
/// reference to this project. They are <c>[Conditional]</c> on a symbol nobody defines: the compiler sees them, the assembly does not.
/// </summary>
internal static class GenerationAttributes
{
    public const string Namespace = "Scott.Mail.Smtp2Go.Generation";
    public const string EndpointTraits = Namespace + ".EndpointTraitsAttribute";
    public const string GeneratedClient = Namespace + ".GeneratedClientAttribute";
    public const string GeneratedWebhookDispatch = Namespace + ".GeneratedWebhookDispatchAttribute";
    public const string GeneratedWebhookUpdate = Namespace + ".GeneratedWebhookUpdateAttribute";

    public const string Source = """
        // <auto-generated/>
        // Marker attributes for Scott.Mail.Smtp2Go.Generators. Conditional on a symbol that is never defined, so they never reach metadata.
        #nullable enable

        namespace Scott.Mail.Smtp2Go.Generation
        {
            /// <summary>
            /// Sets the traits of the matching endpoint descriptors that the API reference does not state. Applied to the partial
            /// <c>EndpointTable</c> in declaration order; each attribute changes only the properties it names. <c>*</c> in the pattern
            /// matches any run of characters. A pattern that matches no documented operation is a build error (SMTP2GO003).
            /// </summary>
            [global::System.AttributeUsage(global::System.AttributeTargets.Class, AllowMultiple = true, Inherited = false)]
            [global::System.Diagnostics.Conditional("SMTP2GO_GENERATION_ATTRIBUTES")]
            internal sealed class EndpointTraitsAttribute : global::System.Attribute
            {
                public EndpointTraitsAttribute(string pathPattern)
                {
                    PathPattern = pathPattern;
                }

                /// <summary>The endpoint path or wildcard pattern, for example <c>stats/*</c> or <c>*/view</c>.</summary>
                public string PathPattern { get; }

                /// <summary>Whether the matching endpoints can be repeated safely.</summary>
                public bool Idempotent { get; set; }

                /// <summary>The documented rate-limit class of the matching endpoints.</summary>
                public global::Scott.Mail.Smtp2Go.Transport.RateLimitClass RateLimit { get; set; }

                /// <summary>The request body limit of the matching endpoints, in bytes.</summary>
                public long MaxBodyBytes { get; set; }
            }

            /// <summary>
            /// Marks a partial client class whose pass-through methods are generated: every method of its interfaces that the class does not
            /// implement itself and has the shape <c>Task&lt;ApiResponse&lt;TData&gt;&gt; M(TRequest request, RequestOptions? options, CancellationToken cancellationToken)</c>
            /// (or the same without the request) becomes a null check and a <c>SendAsync</c> on the connection. The endpoint comes from the
            /// <c>[Smtp2GoEndpoint]</c> on the request type, or on the response data type when there is no request. A method whose endpoint
            /// path is documented with several HTTP methods is not generated and must be written by hand.
            /// </summary>
            [global::System.AttributeUsage(global::System.AttributeTargets.Class, AllowMultiple = false, Inherited = false)]
            [global::System.Diagnostics.Conditional("SMTP2GO_GENERATION_ATTRIBUTES")]
            internal sealed class GeneratedClientAttribute : global::System.Attribute
            {
            }

            /// <summary>
            /// Marks a partial method <c>Task&lt;int&gt; M(WebhookEvent webhookEvent, CancellationToken cancellationToken)</c> whose body
            /// switches on the event's concrete type and calls <c>RunAsync(cancellationToken, Handlers&lt;T&gt;(e), ...)</c> for the
            /// type and each of its bases up to the parameter type, most derived first.
            /// </summary>
            [global::System.AttributeUsage(global::System.AttributeTargets.Method, AllowMultiple = false, Inherited = false)]
            [global::System.Diagnostics.Conditional("SMTP2GO_GENERATION_ATTRIBUTES")]
            internal sealed class GeneratedWebhookDispatchAttribute : global::System.Attribute
            {
            }

            /// <summary>
            /// Marks a static partial method <c>TBase M(TBase value, T1 p1, ...)</c> whose body switches on the concrete type of <c>value</c>
            /// and returns <c>value with { P1 = p1, ... }</c> for every concrete derived record that has a settable property named after each
            /// parameter (PascalCase); other values are returned unchanged.
            /// </summary>
            [global::System.AttributeUsage(global::System.AttributeTargets.Method, AllowMultiple = false, Inherited = false)]
            [global::System.Diagnostics.Conditional("SMTP2GO_GENERATION_ATTRIBUTES")]
            internal sealed class GeneratedWebhookUpdateAttribute : global::System.Attribute
            {
            }
        }
        """;

    public static void Register(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(static context => context.AddSource("Smtp2GoGenerationAttributes.g.cs", SourceText.From(Source, System.Text.Encoding.UTF8)));
    }
}
