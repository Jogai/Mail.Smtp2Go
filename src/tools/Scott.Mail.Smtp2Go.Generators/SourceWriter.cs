using System.Globalization;
using System.Text;
using Microsoft.CodeAnalysis;

namespace Scott.Mail.Smtp2Go.Generators;

/// <summary>Helpers shared by the emitters: the file header, name formats and literal escaping.</summary>
internal static class SourceWriter
{
    public const string ToolName = "Scott.Mail.Smtp2Go.Generators";
    public const string ToolVersion = "1.0.0";

    /// <summary>Fully qualified with <c>global::</c> and nullable annotations, the format every emitted type name uses.</summary>
    public static readonly SymbolDisplayFormat TypeFormat = SymbolDisplayFormat.FullyQualifiedFormat
        .WithMiscellaneousOptions(SymbolDisplayFormat.FullyQualifiedFormat.MiscellaneousOptions | SymbolDisplayMiscellaneousOptions.IncludeNullableReferenceTypeModifier);

    public static StringBuilder Header(string? suppressWarnings = null)
    {
        StringBuilder builder = new();
        builder.AppendLine("// <auto-generated/>");
        builder.AppendLine("// Generated by " + ToolName + ". Do not edit; change the source it is derived from instead.");
        builder.AppendLine("#nullable enable");
        if (suppressWarnings is not null)
        {
            builder.Append("#pragma warning disable ").AppendLine(suppressWarnings);
        }

        builder.AppendLine();
        return builder;
    }

    public static string GeneratedCodeAttribute => "[global::System.CodeDom.Compiler.GeneratedCode(\"" + ToolName + "\", \"" + ToolVersion + "\")]";

    /// <summary>A C# string literal for <paramref name="value"/>.</summary>
    public static string Literal(string value)
    {
        StringBuilder builder = new("\"");
        foreach (char c in value)
        {
            switch (c)
            {
                case '"':
                    builder.Append("\\\"");
                    break;
                case '\\':
                    builder.Append("\\\\");
                    break;
                case '\n':
                    builder.Append("\\n");
                    break;
                case '\r':
                    builder.Append("\\r");
                    break;
                case '\t':
                    builder.Append("\\t");
                    break;
                default:
                    if (c < ' ')
                    {
                        builder.Append("\\u").Append(((int)c).ToString("x4", CultureInfo.InvariantCulture));
                    }
                    else
                    {
                        builder.Append(c);
                    }

                    break;
            }
        }

        return builder.Append('"').ToString();
    }

    public static string Literal(long value)
    {
        return value.ToString(CultureInfo.InvariantCulture) + "L";
    }

    /// <summary>The opening of a partial declaration mirroring <paramref name="type"/>: its namespace and the nesting of containing types.</summary>
    public static void OpenType(StringBuilder builder, INamedTypeSymbol type, out int depth)
    {
        depth = 0;
        if (!type.ContainingNamespace.IsGlobalNamespace)
        {
            builder.Append("namespace ").Append(type.ContainingNamespace.ToDisplayString()).AppendLine(";").AppendLine();
        }

        Stack<INamedTypeSymbol> chain = new();
        for (INamedTypeSymbol? current = type; current is not null; current = current.ContainingType)
        {
            chain.Push(current);
        }

        while (chain.Count > 0)
        {
            INamedTypeSymbol current = chain.Pop();
            Indent(builder, depth).Append("partial ").Append(Keyword(current)).Append(' ').AppendLine(current.Name);
            Indent(builder, depth).AppendLine("{");
            depth++;
        }
    }

    public static void CloseType(StringBuilder builder, int depth)
    {
        while (depth > 0)
        {
            depth--;
            Indent(builder, depth).AppendLine("}");
        }
    }

    public static StringBuilder Indent(StringBuilder builder, int depth)
    {
        return builder.Append(' ', depth * 4);
    }

    /// <summary>The value an interface method's optional parameter gets in the generated implementation.</summary>
    public static string DefaultValue(IParameterSymbol parameter)
    {
        if (!parameter.HasExplicitDefaultValue)
        {
            return string.Empty;
        }

        return parameter.ExplicitDefaultValue is null && !parameter.Type.IsValueType ? " = null" : " = default";
    }

    /// <summary>The <see cref="System.Net.Http.HttpMethod"/> expression for an upper-case method name; <c>PATCH</c> is <c>Endpoint.Patch</c> because netstandard2.0 lacks it.</summary>
    public static string HttpMethodExpression(string method)
    {
        return method switch
        {
            "GET" => "global::System.Net.Http.HttpMethod.Get",
            "POST" => "global::System.Net.Http.HttpMethod.Post",
            "PUT" => "global::System.Net.Http.HttpMethod.Put",
            "DELETE" => "global::System.Net.Http.HttpMethod.Delete",
            "HEAD" => "global::System.Net.Http.HttpMethod.Head",
            "OPTIONS" => "global::System.Net.Http.HttpMethod.Options",
            "TRACE" => "global::System.Net.Http.HttpMethod.Trace",
            "PATCH" => "global::Scott.Mail.Smtp2Go.Transport.Endpoint.Patch",
            _ => "new global::System.Net.Http.HttpMethod(" + Literal(method) + ")",
        };
    }

    private static string Keyword(INamedTypeSymbol type)
    {
        if (type.IsRecord)
        {
            return type.TypeKind == TypeKind.Struct ? "record struct" : "record";
        }

        return type.TypeKind switch
        {
            TypeKind.Struct => "struct",
            TypeKind.Interface => "interface",
            _ => "class",
        };
    }
}
